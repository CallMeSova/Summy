export const DICTS = { th, en };

export function translate(locale, key, vars) {
  let s = (DICTS[locale] && DICTS[locale][key]) ?? DICTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

